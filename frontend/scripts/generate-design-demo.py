"""Package the editorial handoff for the buildless frontend; never call an AI/API."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'demo/scenarios/design-review'
data = json.loads((SOURCE / 'insights-annotations.fixture.json').read_text(encoding='utf-8'))
assert data['fixture_type'] == 'editorial_content_fixture_not_api_response'
records = []
for meeting in data['source_meetings']:
    content = (SOURCE / meeting['file']).read_text(encoding='utf-8')
    paragraphs = []
    for pid, text in re.findall(r'(?m)^([PQ]\d{3}) (.+)$', content):
        speaker, separator, speech = text.partition('：')
        assert separator
        paragraphs.append(dict(id=pid, text=text, speaker=speaker, speech=speech))
    assert len(paragraphs) == meeting['turn_count']
    records.append(dict(meeting_id=meeting['meeting_id'], filename=meeting['file'],
                        title=content.splitlines()[0].removeprefix('# '),
                        content=content, paragraphs=paragraphs))
claims = {item['claim_id']: item for item in data['annotations']}
assert len(claims) == len(data['annotations'])
for claim in claims.values():
    record = next(item for item in records if item['meeting_id'] == claim['meeting_id'])
    paragraph = next(item for item in record['paragraphs'] if item['id'] == claim['paragraph_id'])
    assert claim['quote'] in paragraph['text'], claim['claim_id']
    if claim['relation']:
        assert claim['relation']['target_claim_id'] in claims
output = ROOT / 'frontend/src/fixtures/design-review-data.js'
output.write_text('// Generated by scripts/generate-design-demo.py from the editorial handoff.\n'
                  'export const designReviewData = ' + json.dumps(dict(fixture=data, records=records), ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f'Packaged {len(records)} synthetic texts and {len(claims)} exact references.')
